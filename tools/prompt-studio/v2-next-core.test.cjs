'use strict';
const assert=require('node:assert/strict');
const C=require('./v2-next-core.js');
const s=C.validateState(C.starterState());
assert.equal(s.schema,'prompt-studio-2.0');
assert.equal(s.parts.find(x=>x.id==='character').values.find(x=>x.id==='woman').options.length,3);
assert.equal(s.parts.find(x=>x.id==='character').values.find(x=>x.id==='dog').options[0].name,'犬種');
const character=s.parts.find(x=>x.id==='character');
const location=s.parts.find(x=>x.id==='location');
const woman=character.values.find(x=>x.id==='woman');
const train=location.values.find(x=>x.id==='train');
let draft={text:'{登場人物}が{場所}で{ポーズ}をしている。',marks:[]};
draft=C.reflect(draft,character,woman,{hair:'hair2',body:'body0'});
assert.match(draft.text,/ロング/);
assert.equal(draft.marks.length,1);
draft=C.reflect(draft,location,train,{});
assert.equal(draft.marks.length,2);
assert.equal(C.toTemplate(draft),'{登場人物}が{場所}で{ポーズ}をしている。');
let multiple={text:'{登場人物}と{登場人物}',marks:[]};
multiple=C.reflect(multiple,character,woman,{});
multiple=C.reflect(multiple,character,character.values.find(x=>x.id==='dog'),{});
assert.equal(C.toTemplate(multiple),'{登場人物}と{登場人物}');
assert.equal(multiple.marks.length,2);
const shifted=C.editText(draft,'最初に'+draft.text);
assert.equal(shifted.marks.length,2);
assert.equal(C.toTemplate(shifted),'最初に{登場人物}が{場所}で{ポーズ}をしている。');
const touched=C.editText(draft,draft.text.replace('女性','人間'));
assert.equal(touched.marks.length,1);
assert.equal(C.toTemplate(touched).includes('{登場人物}'),false);
assert.equal(C.addCopy([], 'a','now').length,1);
let copies=[];
for(let i=0;i<7;i++)copies=C.addCopy(copies,String(i),String(i));
assert.deepEqual(copies.map(x=>x.text),['6','5','4','3','2']);
const full=C.starterState();
full.draft=draft;
full.prompts.push({id:'p1',name:'保存',content:'a'});
const restored=C.restore(JSON.parse(C.backup(full)));
assert.deepEqual(restored,full);
assert.throws(()=>C.restore({format:'prompt-db',data:full}),/2.0バックアップ/);
const corrupt=C.clone(full);corrupt.parts[0].values[0].options[0].choices[1].id=corrupt.parts[0].values[0].options[0].choices[0].id;
assert.throws(()=>C.validateState(corrupt),/ID/);
const wrong=C.clone(full);wrong.draft.marks[0].end=wrong.draft.text.length+10;
assert.throws(()=>C.validateState(wrong),/不正/);
console.log('Prompt Studio 2.0 core tests: PASS');

const oldVersionState=C.starterState();
delete oldVersionState.outputMode;
assert.equal(C.validateState(oldVersionState).outputMode,'prose','old browser state migrates without data loss');
assert.equal(C.restore(JSON.parse(C.backup(oldVersionState))).outputMode,'prose');
const invalidMode=C.starterState();invalidMode.outputMode='guess';
assert.throws(()=>C.validateState(invalidMode),/出力形式/);
assert.equal(C.selectionText(woman,{hair:'hair2'},'tags'),'1girl, long hair');
assert.equal(C.selectionText(woman,{hair:'hair2'},'prose'),'女性（髪の長さ：ロング）');
assert.equal(C.selectionText({name:'カスタム',tag:'custom token',options:[{id:'color',name:'色',choices:[{id:'red',name:'赤',tag:'red'}]}]},{color:'red'},'tags'),'custom token, red');
assert.equal(C.selectionText({name:'未知の名前',options:[]},{},'tags'),'未知の名前');
let formatDraft=C.reflect({text:'',marks:[]},character,woman,{hair:'hair2'},'prose');
formatDraft=C.reflect(formatDraft,location,train,{},'prose');
assert.match(formatDraft.text,/、電車$/);
const beforeProse=formatDraft.text;
const expectedTemplate=C.toTemplate(formatDraft);
const tagDraft=C.formatDraft(formatDraft,'tags');
assert.equal(tagDraft.text,'1girl, long hair, train interior');
assert.equal(tagDraft.marks.length,2);
assert.equal(C.toTemplate(tagDraft),expectedTemplate);
assert.deepEqual(C.formatDraft(tagDraft,'prose'),formatDraft);
assert.equal(C.formatDraft(formatDraft,'prose').text,beforeProse);
let withManual=C.reflect({text:'Image of ',marks:[]},character,woman,{},'prose');
const converted=C.formatDraft(withManual,'tags');
assert.equal(converted.text,'Image of , 1girl','manual text is not retranslated; only marked tokens are converted');
assert.equal(C.formatDraft(converted,'prose').text,withManual.text);
const existingTemplate='{登場人物}, {登場人物}';
let repeated=C.reflect({text:existingTemplate,marks:[]},character,woman,{},'tags');
repeated=C.reflect(repeated,character,character.values.find(x=>x.id==='dog'),{},'tags');
assert.equal(repeated.text,'1girl, dog');
assert.equal(C.toTemplate(repeated),existingTemplate);
assert.equal(C.formatDraft(repeated,'prose').text,'女性, 犬','literal template punctuation stays untouched');
const typed=C.editText(tagDraft,'手入力 '+tagDraft.text);
assert.equal(C.formatDraft(typed,'prose').text,'手入力 '+beforeProse,'free-form text is untouched');
const recentWithMode=C.addCopy([],tagDraft.text,'now','tags');
assert.equal(recentWithMode[0].mode,'tags');
assert.equal(C.validateState({...C.starterState(),recentCopies:recentWithMode}).recentCopies[0].mode,'tags');
const savedWithMode=C.starterState();savedWithMode.prompts.push({id:'t',name:'test',content:tagDraft.text,mode:'tags'});
assert.equal(C.restore(JSON.parse(C.backup(savedWithMode))).prompts[0].mode,'tags');
console.log('Prompt Studio 2.0 output format tests: PASS');

