'use strict';
const assert = require('node:assert/strict');
const C = require('./v2-next-core.js');
const base = C.validateState(C.starterState());
assert.equal(base.schema, 'prompt-studio-2.0');
const character = base.parts.find(p=>p.id==='character');
const location = base.parts.find(p=>p.id==='location');
const woman=character.values.find(v=>v.id==='woman');
const dog=character.values.find(v=>v.id==='dog');
const train=location.values.find(v=>v.id==='train');
assert.equal(character.name, '登場人物');
assert.equal(character.en, 'character');
assert.equal(woman.name, '女性');
assert.equal(woman.en, 'a woman');
assert.equal(woman.tag, '1girl');
assert.equal(dog.options[0].name, '犬種');
assert.equal(woman.options[0].choices[2].en,'long hair');
assert.equal(base.templates[0].name,'人物・場所・ポーズ');
assert.equal(base.templates[0].content,'{character} {pose} {location}.');
assert.equal(base.templates[0].previewJa,'{登場人物}が{場所}で{ポーズ}をしている。');
let draft={text:base.templates[0].content,marks:[]};
draft=C.reflect(draft,character,woman,{hair:'hair2',body:'body0'});
assert.match(draft.text,/a woman with long hair and a slim build/);
assert.equal(draft.marks.length,1);
draft=C.reflect(draft,location,train,{});
assert.match(draft.text,/inside a train/);
assert.equal(C.toTemplate(draft,base.parts),'{character} {pose} {location}.');
assert.equal(C.hasJapanese(draft.text),false);
let multiple={text:'{character} and {character}',marks:[]};
multiple=C.reflect(multiple,character,woman,{});
multiple=C.reflect(multiple,character,dog,{});
assert.equal(C.toTemplate(multiple,base.parts),'{character} and {character}');
assert.equal(multiple.marks.length,2);
const shifted=C.editText(draft,'Starting: '+draft.text);
assert.equal(shifted.marks.length,2);
assert.equal(C.toTemplate(shifted,base.parts),'Starting: {character} {pose} {location}.');
const touched=C.editText(draft,draft.text.replace('a woman','a person'));
assert.equal(touched.marks.length,1);
assert.equal(C.toTemplate(touched,base.parts).includes('{character}'),false);
let copies=[];
for(let i=0;i<7;i++)copies=C.addCopy(copies,String(i),String(i));
assert.deepEqual(copies.map(x=>x.text),['6','5','4','3','2']);
const full=C.starterState();
full.draft=draft;
full.prompts.push({id:'p1',name:'保存',content:'a'});
assert.deepEqual(C.restore(JSON.parse(C.backup(full))),C.validateState(full));
assert.throws(()=>C.restore({format:'prompt-db',data:full}),/2.0バックアップ/);
const corrupt=C.clone(full);
corrupt.parts[0].values[0].options[0].choices[1].id=corrupt.parts[0].values[0].options[0].choices[0].id;
assert.throws(()=>C.validateState(corrupt),/ID/);
const wrong=C.clone(full);wrong.draft.marks[0].end=wrong.draft.text.length+10;
assert.throws(()=>C.validateState(wrong),/不正/);
console.log('Prompt Studio 2.0 core tests: PASS');
const oldBackup=C.starterState();
delete oldBackup.outputFormat;
assert.equal(C.validateState(oldBackup).outputFormat,'prose');
let tags={text:'',marks:[]};
tags=C.reflect(tags,character,woman,{hair:'hair2',body:'body0'},'tags');
assert.equal(tags.text,'1girl, long hair, slim body');
tags=C.reflect(tags,location,train,{},'tags');
assert.equal(tags.text,'1girl, long hair, slim body, train interior');
assert.equal(C.toTemplate(tags,base.parts),'{character}, {location}');
tags={text:'{character}, {character}',marks:[]};
tags=C.reflect(tags,character,woman,{},'tags');
tags=C.reflect(tags,character,dog,{},'tags');
assert.equal(C.toTemplate(tags,base.parts),'{character}, {character}');
const tagBackup=C.restore(JSON.parse(C.backup({...full,outputFormat:'tags',draft:tags})));
assert.equal(tagBackup.outputFormat,'tags');
assert.equal(tagBackup.draft.text,tags.text);
assert.equal(C.addCopy([], '1girl, long hair','time','tags')[0].outputFormat,'tags');
assert.equal(C.reflect({text:'',marks:[]},character,woman,{},'prose').text,'a woman');
console.log('Prompt Studio 2.0 format regression: PASS');
const legacy=C.clone(base);
for(const part of legacy.parts){
  delete part.en;
  for(const val of part.values){
    delete val.en;delete val.tag;
    for(const option of val.options){
      delete option.en;
      for(const choice of option.choices){delete choice.en;delete choice.tag;}
    }
  }
}
legacy.templates[0].content='{登場人物}が{場所}で{ポーズ}をしている。';
legacy.templates[1].content='{年代}の{画風}、{登場人物}、{登場人物}、{動き}';
const migrated=C.validateState(legacy);
assert.equal(migrated.parts[0].values[0].en,'a woman');
assert.equal(migrated.parts[0].values[0].options[0].choices[2].en,'long hair');
assert.equal(migrated.templates[0].content,'{character} {pose} {location}.');
assert.equal(migrated.templates[0].previewJa,'{登場人物}が{場所}で{ポーズ}をしている。');
const custom=C.clone(legacy);
custom.parts.push({id:'custom',name:'乗り物',values:[{id:'bus',name:'バス',options:[]}]});
const normalized=C.validateState(custom);
assert.equal(normalized.parts.at(-1).en,'');
assert.equal(normalized.parts.at(-1).values[0].en,'');
assert.throws(()=>C.reflect({text:'',marks:[]},normalized.parts.at(-1),normalized.parts.at(-1).values[0],{},'tags'),/英語変数名/);
assert.throws(()=>C.reflect({text:'日本語の既存文章',marks:[]},character,woman,{},'prose'),/日本語/);
assert.equal(C.hasJapanese('a woman with long hair'),false);
assert.equal(C.hasJapanese('女性'),true);
assert.equal(C.englishKey('character_name'),true);
assert.equal(C.englishKey('登場人物'),false);
console.log('Prompt Studio 2.0 English output and compatibility tests: PASS');
